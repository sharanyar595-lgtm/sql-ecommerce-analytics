-- ---------- Orders (200) ----------
-- Generated with a simple fixed formula (LCG) so results are repeatable.
-- Lower customer_ids order more often, giving a realistic mix of
-- frequent and occasional buyers. Dates span Jan 2025 to Oct 2026.
DECLARE @i INT = 1, @x BIGINT = 42;
DECLARE @a INT, @b INT, @cust INT, @prod INT, @qty INT, @off INT;

WHILE @i <= 200
BEGIN
    SET @x = (@x * 1103515245 + 12345) % 2147483648;  SET @a    = (@x / 65536) % 20;
    SET @x = (@x * 1103515245 + 12345) % 2147483648;  SET @b    = (@x / 65536) % 20;
    SET @x = (@x * 1103515245 + 12345) % 2147483648;  SET @prod = (@x / 65536) % 12 + 1;
    SET @x = (@x * 1103515245 + 12345) % 2147483648;  SET @qty  = (@x / 65536) % 4 + 1;
    SET @x = (@x * 1103515245 + 12345) % 2147483648;  SET @off  = (@x / 65536) % 660;

    SET @cust = CASE WHEN @a < @b THEN @a ELSE @b END + 1;

    INSERT INTO orders (customer_id, product_id, quantity, order_date)
    VALUES (@cust, @prod, @qty, DATEADD(DAY, @off, '2025-01-01'));

    SET @i += 1;
END
GO

